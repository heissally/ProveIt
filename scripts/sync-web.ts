/**
 * npm run web:sync   (also runs automatically before `npm run dev`)
 *
 * Copies what the website needs from the deployed Lit Actions into web/src/generated/:
 *   public-config.json  client IDs, action CIDs, PUBLISHED SIGNER ADDRESSES and the
 *                       Discord servers. Safe for browsers: nothing here is secret.
 *   action-code.json    the exact action source the server function sends to Lit.
 *                       LIT: Chipotle hashes this code to its CID on every call, so it
 *                       must be byte-for-byte the deployed version.
 * Both files are committed, so a Vercel build needs nothing from outside web/.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { readConfig } from "./lib/action-config.ts";
import { loadLitConfig } from "./lib/config.ts";
import { REPO_ROOT, getActionCid, readActionSource } from "./lib/lit-api.ts";
import { loadRegistry } from "./lib/registry.ts";

const lit = await loadLitConfig();
const problems: string[] = [];

const code = {
  google: await readActionSource("lit-actions/proveit-google.js"),
  discord: await readActionSource("lit-actions/proveit-discord.js"),
};

const methods = {} as Record<"google" | "discord", { clientId: string; actionCid: string; signer: string }>;
for (const m of ["google", "discord"] as const) {
  const c = lit[m];
  if (!c.clientId || !c.actionCid || !c.signer) {
    problems.push(`${m}: not deployed yet (run npm run action:deploy -- ${m})`);
    methods[m] = { clientId: c.clientId ?? "", actionCid: c.actionCid ?? "", signer: c.signer ?? "" };
    continue;
  }
  methods[m] = { clientId: c.clientId, actionCid: c.actionCid, signer: c.signer };
  try {
    if ((await getActionCid(code[m])) !== c.actionCid) {
      problems.push(`${m}: lit-actions/proveit-${m}.js changed since the last deploy (run npm run action:deploy -- ${m})`);
    }
  } catch {
    console.log(`  (could not reach Lit to double-check the ${m} CID; continuing)`);
  }
}

// The servers the Discord action actually enforces come from ITS config block;
// the registry file adds the official-source links shown to askers.
const actionServers = readConfig(code.discord).servers ?? {};
const registry = await loadRegistry().catch(() => []);
const servers = Object.entries(actionServers).map(([guildId, s]) => ({
  guildId,
  name: s.name,
  officialSource: registry.find((r) => r.guildId === guildId)?.officialSource ?? "",
  roles: ["Admin", "Mod"].filter((l) => Object.values(s.roles).includes(l)),
}));
if (registry.some((r) => !actionServers[r.guildId])) {
  problems.push("registry/servers.json has servers the deployed Discord action doesn't know yet (run npm run action:deploy -- discord)");
}

const outDir = join(REPO_ROOT, "web/src/generated");
await mkdir(outDir, { recursive: true });
const note = "Generated by `npm run web:sync`. Do not edit by hand.";
await writeFile(join(outDir, "public-config.json"), JSON.stringify({ _note: note, ...methods, servers }, null, 2) + "\n");
await writeFile(join(outDir, "action-code.json"), JSON.stringify({ _note: note, ...code }, null, 2) + "\n");

console.log("\n✓ Synced Lit Action code and public settings into web/src/generated/");
console.log(`  google  ${methods.google.actionCid || "(not deployed)"}  signer ${methods.google.signer || "-"}`);
console.log(`  discord ${methods.discord.actionCid || "(not deployed)"}  signer ${methods.discord.signer || "-"}`);
console.log(`  servers ${servers.map((s) => s.name).join(", ") || "(none)"}`);
for (const p of problems) console.log(`  ⚠ ${p}`);
console.log("");
